SET enabled = FALSE, updated_at = CURRENT_TIMESTAMP
WHERE r.enabled = TRUE
  AND NOT EXISTS (
      SELECT 1 FROM region_catalog_staging_v14 s
      WHERE s.sido_code = r.sido_code AND s.sigungu_code = r.sigungu_code
  );
